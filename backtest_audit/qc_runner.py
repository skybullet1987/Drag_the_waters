"""qc_runner — one-command Pulse deploy + backtest on QuantConnect.

Unlocks Phase 2 (harsh-sim validation) and Phase 3 (walk-forward sweep)
by wrapping the QC API write methods into a high-level workflow.

Workflow:
    1. (optional) Create a QC project, OR re-use an existing one
    2. Push every file in `Pulse/` to the project
    3. Trigger a compile, poll until it succeeds
    4. Trigger a backtest with a chosen name + parameter overrides
    5. Poll until the backtest completes
    6. Return the final stats payload + backtest_id

Usage from CLI:
    python3 backtest_audit/qc_runner.py \\
        --project-id 31410009 \\
        --backtest-name "phase2-harsh-2025" \\
        --start-year 2025 --end-year 2025

Usage from Python:
    from backtest_audit.qc_runner import deploy_pulse, run_backtest
    pid = deploy_pulse(project_name="Pulse-2026")
    bt  = run_backtest(pid, "phase2-harsh-2025",
                       params={"start_year": "2025", "end_year": "2025"})
    print(bt["statistics"])

Notes:
  - Files are read from the local Pulse/ directory and pushed verbatim.
  - QC project's main.py MUST instantiate PulseAlgorithm; we ensure this by
    wrapping `Pulse/main.py` with a minimal entry stub if the project's
    main.py doesn't already import PulseAlgorithm.
  - Parameters are pushed via QC's project parameters JSON (left to caller
    to set in the project panel for now; future improvement: API for params).
"""

