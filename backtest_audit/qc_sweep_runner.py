"""qc_sweep_runner — fully-automated Phase 3 walk-forward sweep on QC.

PLAN.md §5 — runs each (param_set, window) combination as a QC backtest,
collects results, and feeds them into regime_runner.sweep() for survivability
scoring.

Workflow per (param_id, params, window):
    1. Push runtime_overrides.py with the params dict to the QC project
    2. Push start_year / end_year QC parameters (via re-pushing main.py
       with hard-coded dates — see _embed_window_dates)
    3. Trigger compile + backtest via qc_runner.run_backtest
    4. Pull final stats; convert to WindowResult
    5. Optionally pull orders for finer-grained gap analysis

Run-mode flags:
    - dry_run=True   — skip QC calls; emit synthetic WindowResult with
                       random returns. Use for smoke testing.
    - parallel=False — sequential (default; QC backtests are serialized
                       per-account). Future: parallelize across multiple
                       projects.

Output: SweepResult identical to regime_runner.sweep() output.
HTML report writeable via report.render_sweep().

Notes on cloud time:
    - Default 50 param sets × 6 windows = 300 backtests
    - Typical 1-year crypto backtest: 5-15 minutes cloud time
    - Total: 25-75 cloud-hours per full sweep
    - Mitigations: dry_run=True for code paths; --max-windows to subset;
      --max-params to cap the sweep size
"""

